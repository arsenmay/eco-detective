export const DEVICE_MODELS: Readonly<Record<ModelKind, ModelDefinition>> = {
  tower: TOWER, monitor: MONITOR, projector: PROJECTOR, lamp: LAMP, fridge: FRIDGE,
  radiator: RADIATOR, window: WINDOW, network: NETWORK, sensor: SENSOR, ventilation: VENTILATION,
};

/** A model illustrates one passport, never a final-case aggregate of other sources. */
export function getDeviceModel(device: Equipment): ModelDefinition | null {
  if (device.id.startsWith('final-') && device.id !== 'final-server') return null;
  if (device.id === 'hall-sensor') return SENSOR;
  switch (device.category) {
    case 'computer': return TOWER;
    case 'monitor': return MONITOR;
    case 'projector': return PROJECTOR;
    case 'lighting': return LAMP;
    case 'fridge':
    case 'freezer': return FRIDGE;
    case 'ventilation': return VENTILATION;
    case 'heating': return device.id === 'thermal-controller' ? RADIATOR : null;
    case 'window': return WINDOW;
    case 'network': return NETWORK;
    default: return null;
  }
}
